def calcular_area(df, centro, janela):
    cols_wl = [c for c in df.columns if str(c).replace('.', '', 1).isdigit()]

    # Filtra apenas as colunas dentro da janela de integração
    cols_alvo = [c for c in cols_wl if (centro - janela) <= float(c) <= (centro + janela)]

    if not cols_alvo:
        print(f"Aviso: Nenhuma coluna encontrada para o pico {centro} nm!")
        return np.nan

    dados = df[cols_alvo].astype(float)


    area = np.trapezoid(dados, axis=1)

    return np.maximum(area, 1e-9)


