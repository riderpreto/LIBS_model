    var_p = grupo_puro.var(ddof=1)

    for nivel in niveis_adulteracao:
        grupo_adulterado = df_areas[df_areas['Teor_Adulteracao'] == nivel][razao]

        n_a = len(grupo_adulterado)
        var_a = grupo_adulterado.var(ddof=1)

        s_pooled = np.sqrt(((n_p - 1) * var_p + (n_a - 1) * var_a) / (n_p + n_a - 2))

        d_ck = abs(grupo_puro.mean() - grupo_adulterado.mean()) / s_pooled

        linha_resultado[f'0.0 vs {nivel}'] = round(d_ck, 3)

    resultados_dck.append(linha_resultado)

